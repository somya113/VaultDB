const express = require('express');

const PDFDocument = require('pdfkit');

const verifyToken = require('../middleware/authMiddleware');

const { getAllLogs } = require('../config/immudb');


const router = express.Router();


function printable(value) {
  return String(value === undefined || value === null ? '—' : value).replace(/[\r\n]+/g, ' ');
}


function ensureSpace(document, requiredHeight) {
  if (document.y + requiredHeight > document.page.height - 60) document.addPage();
}


function drawTableHeader(document) {
  const columns = [
    { label: 'Timestamp', width: 105 },
    { label: 'User / Role', width: 83 },
    { label: 'Action / Table', width: 78 },
    { label: 'Sensitive', width: 77 },
    { label: 'Query details', width: 195 },
    { label: 'Response / IP', width: 112 },
  ];
  const startX = document.page.margins.left;
  let x = startX;
  document.font('Helvetica-Bold').fontSize(7).fillColor('#ffffff');
  document.rect(startX, document.y, columns.reduce((sum, column) => sum + column.width, 0), 19).fill('#172554');
  columns.forEach((column) => {
    document.fillColor('#ffffff').text(column.label, x + 3, document.y + 5, { width: column.width - 6, height: 12, lineBreak: false });
    x += column.width;
  });
  document.y += 23;
  return columns;
}


function drawRecord(document, record, columns) {
  const queryDetails = typeof record.query_details === 'string' ? record.query_details : JSON.stringify(record.query_details || {});
  const sensitiveText = record.is_sensitive ? '🚨 SENSITIVE' : 'No';
  const values = [
    printable(record.timestamp),
    `${printable(record.user_email)} / ${printable(record.user_role)}`,
    `${printable(record.action)} / ${printable(record.table_accessed)}`,
    sensitiveText,
    printable(queryDetails),
    `${printable(record.response_time_ms)} ms / ${printable(record.ip_address)}`,
  ];
  const startX = document.page.margins.left;
  const rowHeight = Math.max(...columns.map((column, index) => document.heightOfString(values[index], { width: column.width - 6, font: 'Helvetica', fontSize: 6 }))) + 8;
  ensureSpace(document, rowHeight + 4);
  let x = startX;
  values.forEach((value, index) => {
    const color = index === 3 && record.is_sensitive ? '#b91c1c' : '#111827';
    document.font(index === 3 && record.is_sensitive ? 'Helvetica-Bold' : 'Helvetica').fontSize(6).fillColor(color).text(value, x + 3, document.y + 4, { width: columns[index].width - 6, height: rowHeight - 4 });
    x += columns[index].width;
  });
  document.moveTo(startX, document.y + rowHeight).lineTo(startX + columns.reduce((sum, column) => sum + column.width, 0), document.y + rowHeight).strokeColor('#cbd5e1').lineWidth(0.4).stroke();
  document.y += rowHeight;
}


router.get('/pdf', verifyToken, (req, res) => {
  const filters = { user_email: req.query.user_email, date_from: req.query.date_from, date_to: req.query.date_to };
  let records;
  try {
    records = getAllLogs(filters);
  } catch (error) {
    console.error('Preparing audit PDF failed:', error);
    return res.status(500).json({ error: 'Unable to prepare the audit report.' });
  }
  const reportDate = new Date().toISOString().slice(0, 10);
  res.setHeader('Content-Type', 'application/pdf');
  res.setHeader('Content-Disposition', `attachment; filename="VaultDB_Audit_Report_${reportDate}.pdf"`);
  const document = new PDFDocument({ size: 'LETTER', layout: 'landscape', margin: 36, bufferPages: false });
  document.on('error', (error) => {
    console.error('Streaming audit PDF failed:', error);
    if (!res.headersSent) res.status(500).end();
    else res.destroy(error);
  });
  document.pipe(res);
  document.rect(0, 0, document.page.width, 96).fill('#172554');
  document.font('Helvetica-Bold').fontSize(20).fillColor('#ffffff').text('🏦 VaultDB Compliance Report', 36, 26, { width: document.page.width - 72 });
  document.font('Helvetica').fontSize(9).fillColor('#e2e8f0').text(`Generated by: ${printable(req.user.email)}    Generated at: ${new Date().toISOString()}    Cryptographically sealed by ImmuDB`, 38, 64, { width: document.page.width - 76 });
  document.moveTo(36, 101).lineTo(document.page.width - 36, 101).strokeColor('#f59e0b').lineWidth(3).stroke();
  document.y = 114;
  document.font('Helvetica').fontSize(9).fillColor('#111827').text(`Filters: user_email=${printable(filters.user_email || 'all')}; date_from=${printable(filters.date_from || 'all')}; date_to=${printable(filters.date_to || 'all')}`, 36, document.y, { width: document.page.width - 72 });
  document.moveDown(0.4);
  const sensitiveCount = records.filter((record) => record.is_sensitive).length;
  document.font('Helvetica-Bold').text(`Matching records: ${records.length}    Sensitive records: ${sensitiveCount}`, 36, document.y, { width: document.page.width - 72 });
  document.moveDown(0.8);
  let columns = drawTableHeader(document);
  records.forEach((record) => {
    const estimatedHeight = Math.max(...columns.map((column, index) => {
      const queryDetails = typeof record.query_details === 'string' ? record.query_details : JSON.stringify(record.query_details || {});
      const values = [printable(record.timestamp), `${printable(record.user_email)} / ${printable(record.user_role)}`, `${printable(record.action)} / ${printable(record.table_accessed)}`, record.is_sensitive ? '🚨 SENSITIVE' : 'No', printable(queryDetails), `${printable(record.response_time_ms)} ms / ${printable(record.ip_address)}`];
      return document.heightOfString(values[index], { width: column.width - 6, font: 'Helvetica', fontSize: 6 });
    })) + 8;
    if (document.y + estimatedHeight + 4 > document.page.height - 60) {
      document.addPage();
      columns = drawTableHeader(document);
    }
    drawRecord(document, record, columns);
  });
  ensureSpace(document, 34);
  document.moveDown(0.8);
  document.font('Helvetica').fontSize(7).fillColor('#475569').text('Legal notice: This report contains confidential audit information. Handle and retain it in accordance with applicable financial, privacy, and records-retention requirements.', 36, document.y, { width: document.page.width - 72, align: 'center' });
  document.end();
});


module.exports = router;
